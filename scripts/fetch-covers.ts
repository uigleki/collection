/**
 * Fetches true-color cover art from official sources that need no API key,
 * and writes the optimized assets ahead of the build, so the Vite build
 * needs no native dependencies.
 *
 *   AniList (anime + anime films) · Steam CDN (games)
 *
 * Each work's `art` in src/content/catalog.ts names its source; a work
 * without one keeps its typographic panel. For each work it writes:
 *   src/assets/works/<slug>-<width>.avif — the cover at each of WIDTHS
 *   src/data/generated/covers.ts         — its sizes, placeholder hash, credit
 */
import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import sharp from "sharp";
import { rgbaToThumbHash } from "thumbhash";
import { catalog } from "../src/content/catalog.ts";
import type { WorkMeta } from "../src/content/collection.ts";
import type { CoverMeta } from "../src/data/types.ts";

const ROOT = resolve(import.meta.dirname, "..");
const ASSETS = resolve(ROOT, "src/assets/works");
const GEN = resolve(ROOT, "src/data/generated");

/** What a source returns, before the image is processed. */
interface Fetched {
  url: string;
  credit: string;
  sourceUrl: string;
}

async function anilist(search: string): Promise<Fetched> {
  const query = `query($s:String){Media(search:$s,type:ANIME){coverImage{extraLarge} siteUrl}}`;
  const res = await fetch("https://graphql.anilist.co", {
    method: "POST",
    headers: { "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify({ query, variables: { s: search } }),
  });
  if (!res.ok) throw new Error(`AniList ${res.status}`);
  const json = (await res.json()) as {
    data?: {
      Media?: {
        coverImage?: { extraLarge?: string };
        siteUrl?: string;
      };
    };
  };
  const m = json.data?.Media;
  if (!m?.coverImage?.extraLarge) throw new Error("no cover");
  return {
    url: m.coverImage.extraLarge,
    credit: "AniList",
    sourceUrl: m.siteUrl ?? "https://anilist.co",
  };
}

function steam(appid: number): Fetched {
  return {
    url: `https://cdn.cloudflare.steamstatic.com/steam/apps/${appid}/library_600x900_2x.jpg`,
    credit: "Steam",
    sourceUrl: `https://store.steampowered.com/app/${appid}/`,
  };
}

async function download(url: string) {
  const res = await fetch(url, {
    headers: {
      "User-Agent": "perfect-collection/1.0 (personal, non-commercial)",
    },
  });
  if (!res.ok) throw new Error(`download ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

/**
 * The widths each cover is encoded at, capped at the source's own width. A
 * home-page row shows a cover at most 13rem wide, which 320px covers at
 * 1.5x density and 640px at 2x; a work page shows it up to 24rem wide, at
 * 640px. The page's `sizes` attribute (src/ui/Cover.tsx) picks one.
 */
const WIDTHS = [320, 640];

async function process(slug: string, meta: Fetched): Promise<CoverMeta> {
  const raw = await download(meta.url);
  const source = await sharp(raw).metadata();
  const widths = [
    ...new Set(WIDTHS.map((w) => Math.min(w, source.width ?? w))),
  ];
  let height = 0;
  for (const w of widths) {
    const out = await sharp(raw)
      .resize({ width: w })
      .avif({ quality: 60, effort: 6 })
      .toFile(resolve(ASSETS, `${slug}-${w}.avif`));
    height = out.height;
  }
  const width = widths.at(-1) ?? 0;

  // The blurred placeholder is stored as its thumbhash; the page decodes it
  // (src/lib/covers.ts; covers.test.ts next to it explains why).
  const small = await sharp(raw)
    .resize(90, 90, { fit: "inside" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const thumbhash = Buffer.from(
    rgbaToThumbHash(small.info.width, small.info.height, small.data),
  ).toString("base64");

  return {
    slug,
    width,
    height,
    widths,
    thumbhash,
    credit: meta.credit,
    sourceUrl: meta.sourceUrl,
  };
}

/** Writes the generated module, which holds cover data only. Values derived
 *  from it (the by-slug index, the asset URLs) are built in
 *  src/lib/covers.ts. */
async function emit(covers: readonly CoverMeta[]): Promise<void> {
  const body = `// GENERATED by scripts/fetch-covers.ts — do not edit by hand.
import type { CoverMeta } from "../types.ts";

export const covers = ${JSON.stringify(covers, null, 2)} as const satisfies readonly CoverMeta[];
`;
  const file = resolve(GEN, "covers.ts");
  await writeFile(file, body);
  execFileSync("pnpm", ["exec", "biome", "format", "--write", file], {
    cwd: ROOT,
    stdio: "ignore",
  });
}

async function main() {
  await mkdir(ASSETS, { recursive: true });
  await mkdir(GEN, { recursive: true });

  const covers: CoverMeta[] = [];
  let sourced = 0;
  const works: readonly WorkMeta[] = Object.values(catalog.works);
  for (const work of works) {
    const source = work.art;
    if (!source) {
      console.log(`· ${work.slug}  no licensed source — typographic panel`);
      continue;
    }
    sourced++;
    try {
      const meta =
        source.kind === "anilist"
          ? await anilist(source.search)
          : steam(source.appid);
      const cover = await process(work.slug, meta);
      covers.push(cover);
      console.log(
        `✓ ${work.slug}  ${cover.width}x${cover.height}  (${cover.credit})`,
      );
      if (source.kind === "anilist")
        await new Promise((r) => setTimeout(r, 800)); // rate-limit
    } catch (e) {
      console.warn(`✗ ${work.slug}: ${(e as Error).message}`);
    }
  }

  await emit(covers);
  console.log(
    `\nWrote ${covers.length}/${sourced} covers → src/data/generated/covers.ts`,
  );
}

await main();
